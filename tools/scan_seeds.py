"""Generate recomp_scan.toml: function seeds the finder cannot reach on its own.

Thumb functions referenced only through pointer tables (vtables, state and
callback tables): an aligned odd word anywhere in the ROM that points into the
code region at a PUSH {..., lr}.

Output is an overlay (no [program]); recomp.toml stays hand-written.
"""
import struct, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
rom = (root.parent / "Grand Theft Auto Advance (USA).gba").read_bytes()
SHA1 = "742fc0062ad930253ffea449953061381577649e"
CODE_LO, CODE_HI = 0x080000C0, 0x08071C00
u16 = lambda a: struct.unpack_from("<H", rom, a - 0x08000000)[0]

DATA_LO = CODE_HI - 0x08000000      # leaf pointers are only trusted in data tables

def is_return(h):
    return h == 0x4770 or (h & 0xFF87) == 0x4700 or (h & 0xFF00) == 0xBD00

def leaf_ok(t):
    """A stackless leaf: starts right after a return, or after a literal pool
    that follows one, and reaches its own BX LR within a few instructions
    without a call."""
    if not any(is_return(u16(t - k)) for k in (2, 4, 6, 8, 10)):
        return False
    for k in range(0, 24, 2):
        h = u16(t + k)
        if h == 0x4770:
            return True
        if (h & 0xF800) in (0xF000, 0xF800) or (h & 0xFE00) == 0xB400:
            return False
    return False

thumb = {}
leaf = {}
for off in range(0, len(rom) - 3, 4):
    v = struct.unpack_from("<I", rom, off)[0]
    if not (v & 1 and CODE_LO <= v < CODE_HI):
        continue
    t = v & ~1
    if (u16(t) & 0xFF00) == 0xB500:
        thumb.setdefault(t, 0x08000000 + off)
    elif off >= DATA_LO and t % 4 == 0 and leaf_ok(t):
        leaf.setdefault(t, 0x08000000 + off)

out = ['# AUTO-GENERATED by tools/scan_seeds.py - do not edit; rerun the script.',
       '[identity]', f'sha1 = "{SHA1}"', '']
for a, ref in sorted(thumb.items()):
    out += ['[[extra_func]]', f'addr = 0x{a:08X}', 'mode = "thumb"',
            f'note = "pointer-table target (word at 0x{ref:08X}), PUSH-LR prologue"', '']
# Computed jumps inside the routines copied to IWRAM ("add pc, pc, rN" into
# an unrolled run or a table of two-instruction cases): seed the instruction
# after the jump and every instruction that follows an unconditional branch
# in the next 64 words, so each landing point has a decoded body.
import re
arm = {}
cfg = (root / "recomp.toml").read_text(encoding="utf-8")
for m in re.finditer(r"\[\[code_copy\]\]\s+runtime_start = (0x[0-9A-Fa-f]+)\s+source_start\s+= (0x[0-9A-Fa-f]+)\s+size\s+= (0x[0-9A-Fa-f]+)", cfg):
    rt, src, size = (int(x, 16) for x in m.groups())
    word = lambda a: struct.unpack_from("<I", rom, a - rt + src - 0x08000000)[0]
    for a in range(rt, rt + size - 4, 4):
        w = word(a)
        if (w & 0x0FFFF000) != 0x008FF000 or (w >> 28) != 0xE:   # add pc, pc, <op2>
            continue
        arm.setdefault(a + 4, a)
        for b in range(a + 8, min(a + 4 + 64 * 4, rt + size), 4):
            p = word(b - 4)
            if (p & 0xFF000000) == 0xEA000000 or (p & 0x0FFFFFF0) == 0x012FFF10:
                arm.setdefault(b, a)
for a, ref in sorted(arm.items()):
    out += ['[[extra_func]]', f'addr = 0x{a:08X}', 'mode = "arm"',
            f'note = "landing point of the computed jump at 0x{ref:08X}"', '']
for a, ref in sorted(leaf.items()):
    out += ['[[extra_func]]', f'addr = 0x{a:08X}', 'mode = "thumb"',
            f'note = "data-table target (word at 0x{ref:08X}), stackless leaf"', '']
(root / "recomp_scan.toml").write_text("\n".join(out), encoding="utf-8")
print(f"thumb pointer-table seeds: {len(thumb)}   leaf seeds: {len(leaf)}   IWRAM jump landings: {len(arm)}")
